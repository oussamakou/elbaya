import {chromium, expect} from '@playwright/test';
import {createClient} from '@libsql/client';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const base = 'http://localhost:3010';
assert(!process.env.SHOP_DATABASE_URL && !process.env.TURSO_DATABASE_URL && !/^(?:SHOP_DATABASE_URL|TURSO_DATABASE_URL)=.+/m.test(readFileSync('.env.local','utf8')), 'Local database only');
const client = createClient({url:`file:${resolve('.shop/shop.db').replaceAll('\\','/')}`});
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const key = crypto.randomUUID();
const lastName = `QA-${key}`;
const password = readFileSync('.shop/admin-access.txt','utf8').match(/^Password: (.+)$/m)[1];
const errors=[];page.on('pageerror',e=>errors.push(e.message));
async function post(data, origin=base) {return fetch(base+'/api/shop/reservations',{method:'POST',headers:{'Content-Type':'application/json',Origin:origin},body:JSON.stringify(data)});}
try {
  await page.goto(base+'/en/products');
  const actions=page.locator('.pantry-hero-actions');
  const boxes=await actions.locator('a').evaluateAll(links=>links.map(a=>{const r=a.getBoundingClientRect();return {left:r.left,right:r.right,top:r.top,bottom:r.bottom};}));
  assert(boxes[1].left-boxes[0].right>=20 || boxes[1].top-boxes[0].bottom>=16);
  await page.screenshot({path:'.playwright-mcp/shop-actions-fixed.png',fullPage:true});
  await page.getByRole('link',{name:'Pre-order the harvest'}).click();
  await expect(page).toHaveURL(/products\/reserve$/);
  await expect(page.getByLabel('First name',{exact:true})).toBeVisible();
  assert((await page.locator('.reservation-product-image').boundingBox()).width > 450);
  await page.locator('select[name=productId]').selectOption('honey');
  await expect(page.locator('.reservation-product-image img')).toHaveAttribute('src',/honey.svg/);
  await page.screenshot({path:'.playwright-mcp/preorder-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'.playwright-mcp/preorder-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.getByLabel('First name',{exact:true}).fill('Test');
  await page.getByLabel('Last name',{exact:true}).fill(lastName);
  await page.getByLabel('Tunisian phone number').fill('22123456');
  await page.getByLabel('Governorate',{exact:true}).fill('Béja');
  await page.getByLabel('City / locality',{exact:true}).fill('Testour');
  await page.getByLabel('Street address').fill('12 rue de la ferme');
  await page.getByRole('button',{name:'Send my pre-order request'}).click();
  await expect(page.getByRole('heading',{name:'Your request is received.'})).toBeVisible();
  const request = JSON.parse((await client.execute({sql:'SELECT data FROM shop_reservations WHERE data LIKE ?',args:[`%${lastName}%`]})).rows[0].data);
  assert.equal(request.firstName,'Test');assert.equal(request.email,'');assert.equal(request.status,'new');assert.equal(request.address,'12 rue de la ferme, Testour, Béja');assert.equal(request.city,'Testour');
  const data={firstName:'Test',lastName,phone:'22123456',email:'test@example.com',address:'Test address',governorate:'Béja',city:'Testour',productId:'honey',variantId:'jar-250',quantity:2,requestKey:key};
  assert.equal((await post(data,'https://evil.example')).status,403);
  assert.equal((await post({...data,email:'bad-email'})).status,400);
  assert.equal((await post({...data,quantity:0})).status,400);
  assert.equal((await post({...data,firstName:''})).status,400);
  assert.equal((await post({...data,governorate:''})).status,400);
  assert.equal((await post({...data,city:''})).status,400);
  const first=await post(data);assert.equal(first.status,201);const receipt=await first.json();
  assert.deepEqual(await (await post(data)).json(),receipt);
  assert.equal((await post({...data,quantity:3})).status,409);
  await page.goto(base+'/fr/admin');
  await page.getByLabel('Mot de passe',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Ouvrir ma boutique'}).click();
  await page.getByRole('button',{name:/^Précommandes/}).click();
  const card=page.locator('.reservation-inbox-card').filter({hasText:request.id});
  await expect(card).toContainText(lastName);
  await card.getByLabel('Suivi').selectOption('contacted');
  await expect(card.getByLabel('Suivi')).toBeEnabled();
  await page.reload();
  await page.getByRole('button',{name:/^Précommandes/}).click();
  await expect(card.getByLabel('Suivi')).toHaveValue('contacted');
  await page.screenshot({path:'.playwright-mcp/preorder-admin.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: visible form, mobile layout, optional email, persistence, admin follow-up, origin/field validation and duplicate protection.');
} finally {
  await client.execute({sql:'DELETE FROM shop_reservations WHERE data LIKE ?',args:[`%${lastName}%`]});
  await client.execute("DELETE FROM shop_limits WHERE key LIKE 'reservation:%'");
  client.close();await browser.close();
}
